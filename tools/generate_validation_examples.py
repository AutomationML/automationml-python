@dataclass(frozen=True)
class ExampleCase:
    name: str
    size: str
    polarity: str
    title: str
    description: str
    document: CAEXFile


def source_document() -> SourceDocumentInformation:
    return SourceDocumentInformation(
        origin_name="AutomationML SDK validation suite",
        origin_id="automationml-validation-suite",
        origin_version="0.1.0",
        last_writing_date_time=FIXED_DATE,
    )


def caex_file(file_name: str, **kwargs) -> CAEXFile:
    return CAEXFile(
        file_name=file_name,
        superior_standard_versions=["AutomationML 2.1"],
        source_document_information=[source_document()],
        **kwargs,
    )


def attr(
    name: str,
    value: str,
    *,
    id: str | None = None,
    data_type: str = "xs:string",
    unit: str | None = None,
    ref_type: str | None = None,
) -> Attribute:
    return Attribute(
        id=id,
        name=name,
        value=value,
        attribute_data_type=data_type,
        unit=unit,
        ref_attribute_type=ref_type,
    )


def role_req(path: str) -> RoleRequirements:
    return RoleRequirements(ref_base_role_class_path=path)


def ext_if(
    name: str,
    id: str,
    ref: str,
) -> InterfaceClass:
    return InterfaceClass(id=id, name=name, ref_base_class_path=ref)



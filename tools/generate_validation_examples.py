def main() -> None:
    JSON_DIR.mkdir(parents=True, exist_ok=True)
    XML_DIR.mkdir(parents=True, exist_ok=True)
    manifest: list[dict[str, object]] = []

    for example in cases():
        document = example.document
        json_path = JSON_DIR / f"{example.name}.json"
        xml_path = XML_DIR / f"{example.name}.aml"
        json_path.write_text(document.to_aml_json(indent=2) + "\n", encoding="utf-8")
        xml_path.write_text(
            document.to_aml_xml(pretty=True, include_default_change_mode=True),
            encoding="utf-8",
        )
        issues = document.caex_validation_issues()
        code_counts = Counter(issue.code for issue in issues)
        severity_counts = Counter(issue.severity for issue in issues)
        manifest.append(
            {
                "name": example.name,
                "title": example.title,
                "size": example.size,
                "polarity": example.polarity,
                "description": example.description,
                "json": f"json/{json_path.name}",
                "xml": f"xml/{xml_path.name}",
                "expected_valid": severity_counts.get("error", 0) == 0,
                "expected_issue_count": len(issues),
                "expected_error_count": severity_counts.get("error", 0),
                "expected_warning_count": severity_counts.get("warning", 0),
                "expected_issue_counts": dict(sorted(code_counts.items())),
                "expected_severity_counts": dict(sorted(severity_counts.items())),
            }
        )

    (SUITE / "manifest.json").write_text(
        json.dumps({"cases": manifest}, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()

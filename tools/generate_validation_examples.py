def line_module(
    prefix: str,
    name: str,
    system_unit: str,
    role: str,
    id_suffix: str,
) -> InternalElement:
    interfaces = [
        ext_if(
            "MaterialIn",
            f"{prefix}-{id_suffix}-material-in",
            "AutomationMLInterfaceClassLib/MaterialPort",
        ),
        ext_if(
            "MaterialOut",
            f"{prefix}-{id_suffix}-material-out",
            "AutomationMLInterfaceClassLib/MaterialPort",
        ),
        ext_if("Data", f"{prefix}-{id_suffix}-data", "AutomationMLInterfaceClassLib/DataPort"),
    ]
    if role == "SafetyDevice":
        interfaces.append(
            ext_if(
                "Safety",
                f"{prefix}-{id_suffix}-safety",
                "AutomationMLInterfaceClassLib/SafetyPort",
            )
        )
    return InternalElement(
        id=f"{prefix}-{id_suffix}",
        name=name,
        ref_base_system_unit_path=f"SystemUnitClassLib/{system_unit}",
        attributes=[
            attr(
                "mode",
                "automatic",
                ref_type="LineAttributeTypes/Mode",
            )
        ],
        external_interfaces=interfaces,
        role_requirements=[role_req(f"RoleClassLib/{role}")],
    )


